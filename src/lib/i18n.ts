export const DICTS: Record<Locale, Dict> = { en, ru, uk, pl, de, fr, es, pt, tr, zh, ja, ko };

export function isLocale(v: string | undefined | null): v is Locale {
  return !!v && (LOCALES as readonly string[]).includes(v);
}

/** Picks the locale from the cookie, then Accept-Language, then English. */
export function resolveLocale(cookieValue: string | undefined, acceptLanguage: string | null): Locale {
  if (isLocale(cookieValue)) return cookieValue;
  for (const part of (acceptLanguage ?? '').split(',')) {
    const code = part.split(';')[0]!.trim().toLowerCase().split('-')[0];
    if (isLocale(code)) return code;
  }
  return DEFAULT_LOCALE;
}

/** The comment phrase shown for a locale. English uses COMMENT_PHRASE from the config. */
export function phraseFor(locale: Locale, configuredEnglishPhrase: string): string {
  return locale === 'en' ? configuredEnglishPhrase : DICTS[locale].phrase;
}

/** Every phrase the bot accepts, in all languages. */
export function acceptedPhrases(configuredEnglishPhrase: string): string[] {
  return [...new Set([configuredEnglishPhrase, ...LOCALES.map((l) => DICTS[l].phrase)])];
}
